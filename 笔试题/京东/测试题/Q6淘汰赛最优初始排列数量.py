# 把“mod_pow”这一步封装成函数，便于单独测试、复用并保持主流程清晰。
def mod_pow(a, e, mod=MOD):
    
    ans = 1
    while e:
        if e & 1:
            ans = ans*a % mod
        a = a*a % mod
        e >>= 1
    return ans

